def загрузить():
    путь = os.path.join(ROOT, 'assets', 'dtc.enc.js')
    сырой = io.open(путь, encoding='utf-8').read()
    b64 = re.search(r"b64='([^']+)'", сырой).group(1)
    return путь, сырой, b64, json.loads(base64.b64decode(b64).decode('utf-8'))


def новые_строки(db):
    ист = json.load(io.open(os.path.join(ROOT, 'pcode-source', 'acu-kamaz-5490.json'), encoding='utf-8'))
    наши = db['brands']['kamaz']
    итог, нет = {}, []
    for к, в in ист.items():
        if к in наши:
            continue
        узел, вид = УЗЕЛ.get(в['loc']), ВИД.get(в['desc'])
        if not узел or not вид:
            нет.append((к, в))
            continue
        номер = ('ADM3 ' + в['adm3']) if в.get('adm3') else ('MR2 ' + в['mr2'])
        итог[к] = '%s: %s. Код по K-line на КамАЗ-5490: %s.' % (узел, вид, номер)
    return итог, нет


if __name__ == '__main__':
    путь, сырой, b64, db = загрузить()
    итог, нет = новые_строки(db)
    print('добавится', len(итог), 'без перевода', len(нет))
    for к, в in нет:
        print('  НЕТ', к, в)
    for к in sorted(итог, key=lambda x: tuple(map(int, x.split('.'))))[:12]:
        print(' ', к, итог[к])
    if sys.argv[1:] == ['записать'] and not нет:
        db['brands']['kamaz'].update(итог)
        нов = base64.b64encode(json.dumps(db, ensure_ascii=False, separators=(',', ':')).encode('utf-8')).decode('ascii')
        io.open(путь, 'w', encoding='utf-8', newline='').write(сырой.replace(b64, нов, 1))
        print('записано')
